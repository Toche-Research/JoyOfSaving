"""Every number in the paper: the bodies of Tables 1 and 2 and the macros quoted in the prose.

Writes four files:
  out/tables/tbl_linear.tex          body of Table 1 (linear technology), one row per weight theta
  out/tables/tbl_neoclassical.tex  body of Table 2 (neoclassical technology), one row per weight theta
  out/tables/tbl_speed_gamma.tex   body of the appendix table of counts of 'faster than Ramsey' by gamma
  out/macros/numbers.tex               one LaTeX macro definition per number quoted in the text
  out/numbers.txt                       the same macros in plain text, for reading and for comparison
and, through speed_grid(), out/speed_grid.txt, the grid of calibrations behind the statement that the joy of
saving shortens the half-life in a minority of cases.

The two table files hold the body rows only. The paper's tabularray environments read them with their own
GetTblrBody command, and the surrounding header, rules and notes live in tex/joy_of_saving.tex. Running
this script therefore rewrites the numbers of both tables and of the whole text at once.
Run: cd code && PYTHONPATH=. python3 scripts/make_tables.py"""
import os
import numpy as np
from scipy.optimize import brentq
from joy import linear, neoclassical

HERE = os.path.dirname(__file__)
TABDIR = os.path.join(HERE, '..', 'out', 'tables')     # generated table bodies
MACDIR = os.path.join(HERE, '..', 'out', 'macros')     # generated macro definitions
os.makedirs(MACDIR, exist_ok=True)
OUTDIR = os.path.join(HERE, '..', 'out')
R, RHO, GAMMA = 0.05, 0.03, 2.0
THETAS_LIN = (0.0, 0.01, 0.05, 0.1, 0.2, 0.5, 1.0)
THETAS_NEO = (0.0, 0.02, 0.05, 0.1, 0.2, 0.5)
K0_FRAC = 0.5          # transition starts at half the modified-golden-rule capital

macros = {}


def macro(name, value, fmt):
    """Record one number under the name it will carry in the text, formatted as it will be printed.
    Rounding happens here and nowhere else, so the text and the tables round in the same way."""
    macros[name] = fmt.format(value)


def table_linear():
    """Body of Table 1 and the macros of the linear-technology sections: the balanced growth path at each
    weight theta, the weight that doubles the Ramsey growth rate, the impatient consumer (r = 3%, rho = 5%)
    who still accumulates, and the shape of dg/dr over theta."""
    rows = []
    for th in THETAS_LIN:
        d = linear.solve(R, RHO, GAMMA, th)
        rows.append(rf"{th:g} & {d['tau']:.3f} & {100*d['g']:.2f} & {100*d['z']:.2f} & {100*d['saving_rate']:.1f} & "
                    rf"{100*d['r_eff']:.2f} & {100*d['rho_equiv']:.2f} & {d['dg_dr']:.3f} \\")
    with open(os.path.join(TABDIR, 'tbl_linear.tex'), 'w') as f:
        f.write('% generated by code/scripts/make_tables.py; do not edit\n' + '\n'.join(rows) + '\n')
    for th, tag in ((0.1, 'A'), (0.2, 'B'), (1.0, 'C'), (0.01, 'D')):
        d = linear.solve(R, RHO, GAMMA, th)
        macro('linG' + tag, 100 * d['g'], '{:.2f}'); macro('linZ' + tag, 100 * d['z'], '{:.2f}')
        macro('linTau' + tag, d['tau'], '{:.2f}'); macro('linSav' + tag, 100 * d['saving_rate'], '{:.0f}')
        macro('linReff' + tag, 100 * d['r_eff'], '{:.1f}'); macro('linRhoEq' + tag, 100 * d['rho_equiv'], '{:.1f}')
        macro('linDgDr' + tag, d['dg_dr'], '{:.3f}')
    gR = linear.ramsey_growth(R, RHO, GAMMA)
    macro('linGRamsey', 100 * gR, '{:.0f}'); macro('linSavRamsey', 100 * gR / R, '{:.0f}')
    # theta that doubles the Ramsey growth rate
    th2 = brentq(lambda th: linear.growth(R, RHO, GAMMA, th) - 2 * gR, 1e-6, 10)
    macro('linThetaDouble', th2, '{:.2f}')
    d2 = linear.solve(R, RHO, GAMMA, th2); macro('linTauDouble', d2['tau'], '{:.2f}')
    # impatient consumer: r = 3%, rho = 5%
    gi = linear.growth(0.03, 0.05, GAMMA, 0.2); macro('linGImpatient', 100 * gi, '{:.2f}')
    macro('linGRImpatient', 100 * linear.ramsey_growth(0.03, 0.05, GAMMA), '{:.0f}')
    # dg/dr: minimum over theta and the theta where it crosses 1/gamma
    ths = np.logspace(-4, 2, 2000)
    dgdr = np.array([linear.solve(R, RHO, GAMMA, th)['dg_dr'] for th in ths])
    macro('linDgDrMin', dgdr.min(), '{:.3f}'); macro('linDgDrMinTheta', ths[dgdr.argmin()], '{:.3f}')
    cross = ths[np.where(np.diff(np.sign(dgdr - 1 / GAMMA)) != 0)[0]]
    macro('linDgDrCrossTheta', cross[-1], '{:.2f}')
    macro('linDgDrCrossTau', linear.solve(R, RHO, GAMMA, cross[-1])['tau'], '{:.2f}')
    macro('linDgDrLarge', linear.solve(R, RHO, GAMMA, 100.0)['dg_dr'], '{:.2f}')


def table_neoclassical():
    """Body of Table 2 and the macros of the neoclassical sections: the steady state and half-life at each
    weight theta, the threshold weights at which the economy passes the golden rule and at which long-run
    consumption falls back to its Ramsey level, the year the golden rule is crossed on the transition, and
    the grid counts from speed_grid()."""
    e0 = neoclassical.Economy(theta=0.0); ss0 = e0.steady_state()
    rows = []
    ceq = {}
    for th in THETAS_NEO:
        e = neoclassical.Economy(theta=th); ss = e.steady_state()
        tr = e.transition(K0_FRAC * e0.k_mgr, T=5.0, n=6)
        ceq[th] = e.consumption_equivalent(K0_FRAC * e0.k_mgr, T=CEQ_T, n=CEQ_N)
        rows.append(rf"{th:g} & {ss['tau']:.3f} & {ss['k']/e0.k_mgr:.2f} & {100*(ss['fp']-e.delta):.2f} & "
                    rf"{100*ss['saving_rate']:.1f} & {ss['c']/ss0['c']:.3f} & {e.half_life():.1f} & {100*tr['saving_rate'][0]:.1f} & "
                    rf"{100*ceq[th]:.1f} \\")
        tag = {0.0: 'Zero', 0.02: 'A', 0.05: 'B', 0.1: 'C', 0.2: 'D', 0.5: 'E'}[th]
        macro('neoTau' + tag, ss['tau'], '{:.2f}'); macro('neoK' + tag, ss['k'] / e0.k_mgr, '{:.2f}')
        macro('neoKgr' + tag, ss['k'] / e0.k_gr, '{:.2f}')
        macro('neoRet' + tag, 100 * (ss['fp'] - e.delta), '{:.1f}'); macro('neoSav' + tag, 100 * ss['saving_rate'], '{:.1f}')
        macro('neoC' + tag, ss['c'] / ss0['c'], '{:.3f}'); macro('neoCpct' + tag, 100 * (ss['c'] / ss0['c'] - 1), '{:.1f}')
        macro('neoHalf' + tag, e.half_life(), '{:.1f}'); macro('neoSavImpact' + tag, 100 * tr['saving_rate'][0], '{:.0f}')
    with open(os.path.join(TABDIR, 'tbl_neoclassical.tex'), 'w') as f:
        f.write('% generated by code/scripts/make_tables.py; do not edit\n' + '\n'.join(rows) + '\n')
    macro('neoThetaGR', e0.rho / (e0.rho + e0.delta) * (e0.alpha / (1 - e0.alpha)) ** e0.gamma, '{:.3f}')
    macro('neoTauGR', e0.rho / (e0.rho + e0.delta), '{:.3f}')
    macro('neoKgrOverKmgr', e0.k_gr / e0.k_mgr, '{:.2f}')
    macro('neoSavMGR', 100 * ss0['saving_rate'], '{:.1f}'); macro('neoSavGR', 100 * e0.alpha, '{:.0f}')
    cgr = e0.f(e0.k_gr) - e0.delta * e0.k_gr; macro('neoCgrPct', 100 * (cgr / ss0['c'] - 1), '{:.1f}')
    # theta beyond which long-run consumption falls below its modified-golden-rule level
    f = lambda th: neoclassical.Economy(theta=th).steady_state()['c'] - ss0['c']
    th_c = brentq(f, 1.5 * float(macros['neoThetaGR']), 50.0)
    macro('neoThetaCbelow', th_c, '{:.2f}')
    macro('neoTauCbelow', neoclassical.Economy(theta=th_c).steady_state()['tau'], '{:.2f}')
    macro('neoKCbelow', neoclassical.Economy(theta=th_c).steady_state()['k'] / e0.k_mgr, '{:.2f}')
    # calibration constants
    macro('neoAlphaInv', 1 / e0.alpha, '{:.0f}')
    macro('neoKzeroFrac', 100 * K0_FRAC, '{:.0f}')
    # year at which capital passes the golden rule on the transition from K0_FRAC k_MGR, theta = 0.2
    tr = neoclassical.Economy(theta=0.2).transition(K0_FRAC * e0.k_mgr, T=200.0, n=20001)
    macro('neoCrossGRyearD', tr['t'][np.argmax(tr['k'] > e0.k_gr)], '{:.0f}')
    # half-life at the golden-rule threshold
    e_gr = neoclassical.Economy(theta=float(macros['neoThetaGR']))
    macro('neoHalfGR', e_gr.half_life(), '{:.1f}')
    # speed of adjustment relative to Ramsey over a grid of parameters: the joy of saving does not always slow
    # the adjustment; count the cases in which the half-life is shorter than under Ramsey (same rho, delta,
    # gamma, alpha), and report the grid
    n_cases, n_faster, by_gamma, cases_by_gamma, by_gamma_top_alpha = speed_grid()
    table_speed_gamma(n_cases, n_faster, by_gamma, cases_by_gamma, by_gamma_top_alpha)
    macro('neoGridCases', n_cases, '{:d}'); macro('neoGridFaster', n_faster, '{:d}')
    macro('neoGridFasterPct', 100 * n_faster / n_cases, '{:.0f}')
    macro('neoGridFasterGammaFive', by_gamma[5.0], '{:d}'); macro('neoGridFasterGammaTwo', by_gamma[2.0], '{:d}')
    macro('neoGridFasterGammaLow', by_gamma[0.5] + by_gamma[1.0], '{:d}')
    macro('neoGridRhoLo', 100 * GRID_RHO[0], '{:.0f}'); macro('neoGridRhoHi', 100 * GRID_RHO[-1], '{:.0f}')
    macro('neoGridDeltaLo', 100 * GRID_DELTA[0], '{:.0f}'); macro('neoGridDeltaHi', 100 * GRID_DELTA[-1], '{:.0f}')
    macro('neoGridGammaLo', GRID_GAMMA[0], '{:g}'); macro('neoGridGammaHi', GRID_GAMMA[-1], '{:g}')
    macro('neoGridAlphaLo', GRID_ALPHA[0], '{:g}'); macro('neoGridAlphaHi', GRID_ALPHA[-1], '{:g}')
    macro('neoGridThetaLo', GRID_THETA[0], '{:g}'); macro('neoGridThetaHi', GRID_THETA[-1], '{:g}')
    # the consumption-equivalent gain of the joy-counting planner over the Ramsey planner from the same
    # initial capital, in per cent of the Ramsey consumption path, and the horizon it is computed over
    for th in THETAS_NEO:
        macro('neoCeq' + {0.0: 'Zero', 0.02: 'A', 0.05: 'B', 0.1: 'C', 0.2: 'D', 0.5: 'E'}[th],
              100 * ceq[th], '{:.1f}')
    macro('neoCeqT', CEQ_T, '{:.0f}')


GRID_RHO = (0.01, 0.03, 0.06)
GRID_DELTA = (0.02, 0.05, 0.10)
GRID_GAMMA = (0.5, 1.0, 2.0, 5.0)
GRID_ALPHA = (0.25, 1 / 3, 0.5, 0.7)
GRID_THETA = (0.001, 0.01, 0.1, 1.0, 10.0, 50.0)


TIE = 1e-9          # half-lives closer than this are ties, not speed-ups
CEQ_T, CEQ_N = 200.0, 20001     # horizon and grid of the consumption-equivalent integral


def speed_grid():
    """Number of (rho, delta, gamma, alpha, theta) cases and the number in which the half-life of the stable
    root is shorter with the joy of saving than under Ramsey with the same (rho, delta, gamma, alpha).
    Returns the two totals, the count of speed-ups by gamma, the number of cases by gamma, and the count
    of speed-ups by gamma at the highest capital share in the grid; the last two are what the table of
    counts needs, and no caller has to re-read the grid to get them."""
    n_cases = n_faster = 0
    by_gamma = {g: 0 for g in GRID_GAMMA}
    cases_by_gamma = {g: 0 for g in GRID_GAMMA}
    by_gamma_top_alpha = {g: 0 for g in GRID_GAMMA}
    alpha_top = max(GRID_ALPHA)
    with open(os.path.join(OUTDIR, 'speed_grid.txt'), 'w') as f:
        f.write('rho delta gamma alpha theta half_life_ramsey half_life_joy faster\n')
        for rho in GRID_RHO:
            for delta in GRID_DELTA:
                for gamma in GRID_GAMMA:
                    for alpha in GRID_ALPHA:
                        h0 = neoclassical.Economy(rho=rho, delta=delta, gamma=gamma, alpha=alpha, theta=0.0).half_life()
                        for th in GRID_THETA:
                            h1 = neoclassical.Economy(rho=rho, delta=delta, gamma=gamma, alpha=alpha, theta=th).half_life()
                            # A strict comparison would decide on rounding: at rho=0.03, delta=0.02,
                            # gamma=5 and a capital share of a half the stable root is exactly one per
                            # cent with and without the motive, so six cases differ by less than 1e-13.
                            # The next real difference in the grid is 3.7e-3, so any tolerance between
                            # 1e-12 and 1e-4 gives the same count.
                            faster = h1 < h0 - TIE
                            n_cases += 1; n_faster += int(faster); by_gamma[gamma] += int(faster)
                            cases_by_gamma[gamma] += 1
                            if alpha == alpha_top:
                                by_gamma_top_alpha[gamma] += int(faster)
                            f.write(f'{rho:g} {delta:g} {gamma:g} {alpha:.4f} {th:g} {h0:.4f} {h1:.4f} {int(faster)}\n')
    return n_cases, n_faster, by_gamma, cases_by_gamma, by_gamma_top_alpha


def table_speed_gamma(n_cases, n_faster, by_gamma, cases_by_gamma, by_gamma_top_alpha):
    """Body of the table of counts of 'faster than Ramsey' by gamma across the grid: one row per gamma,
    then the totals. Columns: gamma; the number of cases at that gamma; the number of them in which the
    half-life is shorter with the joy of saving; that number as a percentage of the cases; and how many
    of the speed-ups occur at the highest capital share in the grid. Generated here so that the sentence
    in the text and this table cannot drift apart."""
    rows = [rf"{g:g} & {cases_by_gamma[g]} & {by_gamma[g]} & {100*by_gamma[g]/cases_by_gamma[g]:.1f} & "
            rf"{by_gamma_top_alpha[g]} \\" for g in GRID_GAMMA]
    rows.append(r"\midrule")
    rows.append(rf"all & {n_cases} & {n_faster} & {100*n_faster/n_cases:.1f} & "
                rf"{sum(by_gamma_top_alpha.values())} \\")
    with open(os.path.join(TABDIR, 'tbl_speed_gamma.tex'), 'w') as f:
        f.write('% generated by code/scripts/make_tables.py; do not edit\n' + '\n'.join(rows) + '\n')


def write_macros():
    """Write every recorded number as a LaTeX macro to out/macros/numbers.tex, which the paper inputs in its
    preamble, and the same list in plain text to out/numbers.txt."""
    with open(os.path.join(MACDIR, 'numbers.tex'), 'w') as f:
        f.write('% generated by code/scripts/make_tables.py; do not edit\n')
        for k, v in macros.items():
            f.write(f'\\newcommand{{\\{k}}}{{{v}}}\n')
    with open(os.path.join(OUTDIR, 'numbers.txt'), 'w') as f:
        for k, v in macros.items():
            f.write(f'{k} = {v}\n')


if __name__ == '__main__':
    os.makedirs(TABDIR, exist_ok=True); os.makedirs(OUTDIR, exist_ok=True)
    table_linear(); table_neoclassical(); write_macros()
    print('\n'.join(f'{k} = {v}' for k, v in macros.items()))
