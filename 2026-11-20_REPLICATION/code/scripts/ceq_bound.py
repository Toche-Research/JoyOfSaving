"""Macros for the note to Table 2 (neoclassical technology): where the consumption-equivalent gain ceases to
exist, and how close to that bound the joy-of-saving value lies at theta = 0.5.

At gamma > 1 felicity in consumption is bounded above, so the value of the Ramsey path with its consumption
scaled up by 1 + mu, valued by the criterion that counts the joy of saving at theta, has a finite supremum as
mu -> infinity: the consumption term c^(1-g)/(1-g) tends to 0. The equivalent gain of make_tables.py exists
if and only if the joy-of-saving planner's own value is below that supremum. This script computes
  neoCeqThetaMax   the theta at which the joy-of-saving value equals the supremum (above it, no gain exists)
  neoCeqFrac       at theta = 0.5, (V_joy - V_R)/(sup - V_R): the fraction of the way from the Ramsey value to
                   the supremum at which the joy-of-saving value lies
with the same initial capital (half the modified golden rule), horizon and time grid as the equivalent gain in
Table 2 (make_tables.py), and checks that consumption_equivalent() agrees (finite below the bound, nan above).

Writes out/macros/ceq_bound.tex. Run: cd code && PYTHONPATH=. python3 scripts/ceq_bound.py"""
import os
import sys

import numpy as np
from scipy.optimize import brentq

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from joy import neoclassical          # noqa: E402
import make_tables as mt              # noqa: E402  (K0_FRAC, CEQ_T, CEQ_N: the settings of Table 2)

MACDIR = os.path.join(HERE, '..', 'out', 'macros')
os.makedirs(MACDIR, exist_ok=True)

e0 = neoclassical.Economy(theta=0.0)
K0 = mt.K0_FRAC * e0.k_mgr
ramsey_tr = e0.transition(K0, T=mt.CEQ_T, n=mt.CEQ_N)
ramsey_ss = e0.steady_state()


def values(theta):
    """(V_R, sup, V_joy) under the criterion with weight theta: the Ramsey path, its supremum as its
    consumption is scaled without bound, and the joy-of-saving planner's own path."""
    e = neoclassical.Economy(theta=theta)
    assert e.gamma > 1
    v_r = e.path_value(ramsey_tr, ramsey_ss['c'], ramsey_ss['s'])
    # scale_c -> infinity: c^(1-g) -> 0, so felicity in consumption tends to -1/(1-g); evaluate the limit
    # exactly by valuing the path with a consumption scale large enough that c^(1-g) underflows relative to
    # 1, and confirm against two scales
    sups = [e.path_value(ramsey_tr, ramsey_ss['c'], ramsey_ss['s'], scale_c=sc) for sc in (1e12, 1e14)]
    assert abs(sups[0] - sups[1]) < 1e-9 * max(1.0, abs(sups[1]))
    tr_j, ss_j = e.transition(K0, T=mt.CEQ_T, n=mt.CEQ_N), e.steady_state()
    v_j = e.path_value(tr_j, ss_j['c'], ss_j['s'])
    return v_r, sups[1], v_j


def gap(theta):
    v_r, sup, v_j = values(theta)
    return sup - v_j


theta_max = brentq(gap, 0.5, 0.7, xtol=1e-10)
v_r, sup, v_j = values(0.5)
frac = (v_j - v_r) / (sup - v_r)

# consistency with the equivalent gain of Table 2: finite just below the bound, nan just above
assert np.isfinite(neoclassical.Economy(theta=theta_max - 1e-3).consumption_equivalent(K0, T=mt.CEQ_T, n=mt.CEQ_N))
assert np.isnan(neoclassical.Economy(theta=theta_max + 1e-3).consumption_equivalent(K0, T=mt.CEQ_T, n=mt.CEQ_N))

lines = [
    '% generated by code/scripts/ceq_bound.py; do not edit',
    '\\newcommand{\\neoCeqThetaMax}{%.2f}%% theta above which the equivalent gain does not exist (%.6f)'
    % (theta_max, theta_max),
    '\\newcommand{\\neoCeqFrac}{%.2f}%% at theta = 0.5, (V_joy - V_R)/(sup - V_R) (%.6f)' % (frac, frac),
]
with open(os.path.join(MACDIR, 'ceq_bound.tex'), 'w') as fh:
    fh.write('\n'.join(lines) + '\n')
print('theta_max = %.6f   frac at theta = 0.5 = %.6f' % (theta_max, frac))
