"""Numbers quoted in the proposed subsection on mental accounting, written as LaTeX macros.
Every value is computed here from the closed forms (ma_common) or by re-running the solvers of
ma_temptation.py. Output: code/out/ma/ma_macros.tex (and a plain-text echo ma_macros.txt)."""
import os
import sys
import numpy as np
from scipy.optimize import minimize_scalar

sys.path.insert(0, os.path.dirname(__file__))
from ma_common import (jos_h, jos_dh_dx, jos_tau, z_ramsey, cramsey_multiplier, rho_prime)

OUTD = os.path.join(os.path.dirname(__file__), '..', 'out', 'ma')
G, RHO, R, TH = 2.0, 0.03, 0.05, 0.2
mac = []


def M(name, val, fmt, comment):
    s = format(val, fmt)
    mac.append((name, s, comment))


# calibration with 2 points of gains (y = 3%): the rule binds in the limit
x = 0.02; y = R - x
M('maZR', 100 * z_ramsey(R, RHO, G), '.0f', 'Ramsey consumption-wealth ratio z_R, per cent')
M('maYieldB', 100 * y, '.0f', 'yield with 2 points of gains, per cent')
M('maMultB', cramsey_multiplier(y, x, RHO, G), '.2f', 'normalized multiplier of the rule, 1 - y/rho\'')
h = jos_h(TH, y, x, RHO, G)
M('maTauB', jos_tau(TH, y, x, RHO, G), '.2f', 'tau at theta = 0.2, y = 3%')
M('maMPCformB', 1 + jos_dh_dx(TH, y, x, RHO, G), '.2f', 'MPC out of a shift from gains to yield, theta = 0.2, y = 3%')
q = (y - h) / h; tau = jos_tau(TH, y, x, RHO, G)
M('maMPCtrB', tau * q / (1 + tau * q), '.2f', 'within-period MPC tau q/(1+tau q), theta = 0.2, y = 3%')
for th, nm in [(1e-4, 'maMPCformBsmall'), (1e-8, 'maMPCformBtiny')]:
    M(nm, 1 + jos_dh_dx(th, y, x, RHO, G), '.2f', f'MPC form, theta = {th:g}, y = 3%')
M('maTauBtiny', jos_tau(1e-8, y, x, RHO, G), '.3f', 'tau at theta = 1e-8, y = 3%')
# all-yield calibration (slack)
x0 = 0.0; y0 = R
M('maMPCformS', 1 + jos_dh_dx(TH, y0, x0, RHO, G), '.2f', 'MPC form, theta = 0.2, x = 0')
M('maMPCformSsmall', 1 + jos_dh_dx(1e-4, y0, x0, RHO, G), '.3f', 'MPC form, theta = 1e-4, x = 0')
# temptation, homothetic: ideal yield


def gp_hom_z(yv, r, rho, g, psi):
    from scipy.optimize import brentq
    kap = psi / (1 + psi)
    target = rho - (1 - g) * r
    Phi = lambda z: g * z - kap * yv ** (1 - g) * z ** g - target
    if Phi(yv) <= 0:
        return yv
    return brentq(Phi, 1e-12, yv, xtol=1e-15, rtol=1e-15)


def gp_hom_value(a, yv, r, rho, g, psi):
    from ma_common import pv_iso
    z = gp_hom_z(yv, r, rho, g, psi)
    return (1 + psi) * pv_iso(z * a, r - z, rho, g) - psi * pv_iso(yv * a, r - z, rho, g)


ys = []
for psi in [0.05, 0.2, 1.0]:
    res = minimize_scalar(lambda yy: -gp_hom_value(1.0, yy, R, RHO, G, psi), bounds=(0.001, R), method='bounded',
                          options=dict(xatol=1e-12))
    ys.append(res.x)
M('maGPidealY', 100 * max(ys), '.2f', 'ideal yield of the temptation consumer (max over psi = 0.05, 0.2, 1), per cent')
M('maGPidealYmin', 100 * min(ys), '.2f', 'same, min over psi')
z = gp_hom_z(R, R, RHO, G, 0.05)
M('maGPzSlack', 100 * z, '.2f', 'temptation consumer c/a with psi = 0.05, y = r = 5%, per cent')

with open(os.path.join(OUTD, 'ma_macros.tex'), 'w') as fh:
    fh.write('% Generated by code/scripts/ma_macros.py; do not edit by hand.\n')
    for n, s, c in mac:
        fh.write(f'\\newcommand{{\\{n}}}{{{s}}}% {c}\n')
with open(os.path.join(OUTD, 'ma_macros.txt'), 'w') as fh:
    for n, s, c in mac:
        fh.write(f'{n} = {s}   ({c})\n')
for n, s, c in mac:
    print(f'{n} = {s}   ({c})')
